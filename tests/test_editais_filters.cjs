'use strict';
const assert = require('node:assert/strict');
const model = require('../static/editais-data.js');
const now = '2026-11-22';
const find = (filters) => model.items.filter(e => model.matches(e, filters, now));
assert.equal(model.items.length, 10);
assert.deepEqual(find({uf:'MA',national:true}).map(e=>e.id), ['fapema','amazonia','cnpq','finep','embrapii','bndes','capes']);
assert.deepEqual(find({uf:'MA',national:false}).map(e=>e.id), ['fapema','amazonia']);
assert(!find({region:'amazon',national:false}).some(e=>e.id==='faperj'));
assert(find({region:'amazon',national:false}).some(e=>e.id==='confap'));
assert.deepEqual(find({q:'MOBILIDADE OR lelia'}).map(e=>e.id), ['fapema','cnpq']);
assert(find({q:'amazonia biodiversidade'}).length===0);
assert.equal(model.days('2026-11-22',now),0);
assert.equal(model.days('2026-11-21',now),-1);
assert.equal(model.days(null,now),null);
const fake={...model.items[0],deadline:'2026-11-21'};
assert.equal(model.matches(fake,{term:'urgent'},now),false);
for(const [amount,band] of [[30000,'micro'],[30001,'small'],[100000,'small'],[100001,'medium'],[400000,'medium'],[400001,'large'],[0,'none']])assert(model.matches({...fake,amount},{money:band},now));
assert(!model.matches({...fake,amount:null},{money:'micro'},now));
assert(!model.matches({...fake,deadline:null},{term:'urgent'},now));
assert(model.matches({...fake,deadline:null},{term:'continuous'},now));
assert(find({radar:'scholarships'}).every(e=>e.scholarships.length));
assert(find({radar:'urgent'}).every(e=>model.days(e.deadline,now)>=0&&model.days(e.deadline,now)<=15));
assert.equal(find({uf:'MA',national:false,agency:'FAPERJ'}).length,0);
assert.equal(find({money:'none'})[0].id,'capes');
console.log('OK: território, busca OR/AND, datas, limites financeiros, radar e combinação de filtros.');
